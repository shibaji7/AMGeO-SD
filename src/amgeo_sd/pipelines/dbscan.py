"""DBSCAN / Gaussian-mixture model: fitacf files -> labelled echoes -> fitacf++ (legacy ``fitacf_amgeo_dbcluster.py``)."""

from __future__ import annotations

import datetime as dt
import os
import sys
from collections.abc import Sequence

import numpy as np
from loguru import logger

from amgeo_sd import __version__, export
from amgeo_sd.clustering import cluster_scans
from amgeo_sd.config import Dbscan, Geometry, Input, Output, Run, Settings, dump_settings_toml
from amgeo_sd.geo import radar_fov
from amgeo_sd.io import FitacfReader, fitacfpp_name, scans_to_records, write_fitacfpp
from amgeo_sd.io.summary import estimate_scan_info


def run_dbscan_model(
    rad: str,
    start: dt.datetime,
    end: dt.datetime,
    *,
    files: Sequence[str | os.PathLike] | None = None,
    root: str | os.PathLike | None = None,
    ftype: str = "fitacf",
    params: Dbscan | None = None,
    geometry: str = "legacy",
    altitude: float = 300.0,
    out_base: str | os.PathLike = "data/outputs",
    sim_id: str = "L101",
    write_netcdf: bool = True,
    write_fitacf: bool = True,
    input_paths: Sequence[str | os.PathLike] | None = None,
    argv: Sequence[str] | None = None,
) -> dict:
    """Run the DBSCAN / GMM model for one radar and time window.

    Reads the scans in ``[start, end]``, labels every echo with ``cluster_tag`` and ``gflg_ribiero``
    (:func:`amgeo_sd.clustering.cluster_scans`) and writes ``<rad>_<start>_<end>.fitacf++.nc`` and
    ``<YYYYMMDD.HHMM.SS>.<rad>.fitacf.pl.bz2`` plus ``params.toml`` / ``script.cmd`` to ``<out_base>/<sim_id>/<rad>/``.
    The echoes themselves are the raw fitacf echoes; the ``.fitacf.pl.bz2`` keeps every original record.

    Returns a dict with ``scan_info``, ``n_scans``, ``n_echoes``, ``n_clusters`` (beam, label pairs without noise),
    ``fraction_ground`` / ``fraction_noise`` of the echoes, ``out_dir``, ``nc_file`` / ``fitacf_file`` and ``scans``.
    """
    p = params or Dbscan()
    logger.info(f"dbscan model: {rad} {start} -> {end}")
    probe = FitacfReader(rad, start, start + dt.timedelta(minutes=5), ftype, files, root).beams()
    if not probe:
        raise RuntimeError(f"no {ftype} data for {rad} at {start}")
    scan_info = estimate_scan_info(probe)
    logger.info(f"scan info: {scan_info}")
    reader = FitacfReader(rad, start, end, ftype, files, root)
    scans = [s for s in reader.scans(scan_info["s_mode"]) if any(b.n_echoes for b in s.beams)]
    if not scans:
        raise RuntimeError("no scans with echoes in the time range")
    cluster_scans(scans, scan_info, p)

    echoes = [b for s in scans for b in s.beams if b.n_echoes]
    tags = np.concatenate([b.extra["cluster_tag"] for b in echoes])
    flags = np.concatenate([b.extra["gflg_ribiero"] for b in echoes])
    pairs = {(b.bmnum, b.channel, int(t)) for b in echoes for t in np.unique(b.extra["cluster_tag"]) if t >= 0}
    out = {
        "scan_info": scan_info,
        "n_scans": len(scans),
        "n_echoes": int(len(tags)),
        "n_clusters": len(pairs),
        "fraction_ground": float((flags == 1).mean()),
        "fraction_noise": float((tags < 0).mean()),
        "scans": scans,
    }
    logger.info(
        f"{len(scans)} scans, {len(tags)} echoes, {len(pairs)} clusters, {100 * out['fraction_noise']:.1f}% noise"
    )

    out_dir = export.output_dir(out_base, sim_id, rad)
    out["out_dir"] = str(out_dir)
    command = "python " + " ".join(argv if argv is not None else sys.argv)
    if write_netcdf:
        first = probe[0]
        fov = radar_fov(rad, start, frang=first.frang, rsep=first.rsep, altitude=altitude, backend=geometry)
        calgo = f"GMM ({p.gmm}) - DBSCAN" if p.gmm else "DBSCAN"
        attrs = {
            "rad": rad,
            "start": start,
            "end": end,
            "ftype": ftype,
            "sim_id": sim_id,
            **scan_info,
            "type": "sub-auroral",
            "gflg_type": "us_c",
            "gflg_type_desc": f"Generated by clustering algo ({calgo}).",
            "geometry_backend": geometry,
            "geometry_altitude": altitude,
            "description": f"fitacf++: raw echoes labelled with {calgo} clusters (cluster_tag) and the Ribiero ground scatter flag (gflg_ribiero)",
            **{f"dbscan_{k}": v for k, v in vars(p).items()},
        }
        out["nc_file"] = str(
            export.write_netcdf(
                export.scans_to_dataset(scans, fov, attrs),
                out_dir / f"{rad}_{start:%Y%m%d%H%M}_{end:%Y%m%d%H%M}.fitacf++.nc",
            )
        )
        logger.info(f"wrote {out['nc_file']}")
    if write_fitacf:
        records = scans_to_records(scans, reader.records(), command, model="dbscan", keep_empty=True)
        out["fitacf_file"] = str(write_fitacfpp(out_dir / fitacfpp_name(rad, start), records))
        logger.info(f"wrote {out['fitacf_file']} ({len(records)} records)")

    settings = Settings(
        run=Run(rad, start, end, sim_id, str(out_base), 1),
        input=Input(
            [str(f) for f in (input_paths if input_paths is not None else files or [])],
            str(root) if root else None,
            ftype,
        ),
        dbscan=p,
        geometry=Geometry(geometry, altitude),
        output=Output(write_netcdf, write_fitacf),
    )
    provenance = {
        "command": command,
        "software_version": __version__,
        "created_utc": dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%S"),
    }
    result = {
        "scan_period_min": scan_info["s_time"],
        "themis_beam": scan_info["t_beam"],
        "scan_mode": scan_info["s_mode"],
        "n_scans": out["n_scans"],
        "n_echoes": out["n_echoes"],
        "n_clusters": out["n_clusters"],
        "fraction_ground": round(out["fraction_ground"], 4),
        "fraction_noise": round(out["fraction_noise"], 4),
        **{k: v for k, v in out.items() if k in ("nc_file", "fitacf_file")},
    }
    export.save_run_metadata(
        argv if argv is not None else sys.argv,
        dump_settings_toml(
            settings,
            "AMGeO-SD DBSCAN / GMM run",
            provenance,
            result,
            tables=("run", "input", "dbscan", "geometry", "output"),
        ),
        out_dir,
    )
    return out


def run_dbscan_from_settings(settings: Settings, argv: Sequence[str] | None = None) -> dict:
    """:func:`run_dbscan_model` with the parameters of a :class:`~amgeo_sd.config.Settings`."""
    from amgeo_sd.cli import expand_fitacf_paths

    r, i, o = settings.run, settings.input, settings.output
    return run_dbscan_model(
        r.rad,
        r.start,
        r.end,
        files=expand_fitacf_paths(i.paths) if i.paths else None,
        root=i.root or None,
        ftype=i.ftype,
        params=settings.dbscan,
        geometry=settings.geometry.backend,
        altitude=settings.geometry.altitude,
        out_base=r.out,
        sim_id=r.sim_id,
        write_netcdf=o.netcdf,
        write_fitacf=o.fitacf,
        input_paths=i.paths,
        argv=argv,
    )
