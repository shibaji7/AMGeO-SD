def generate(root: str | Path) -> dict[Path, str]:
    """Return every generated API file as ``{path: text}``.

    Parameters
    ----------
    root : path
        The ``docs`` directory the files belong to.

    Returns
    -------
    dict
        ``root/API.md`` and ``root/api/<slug>.md`` for each page.
    """
    root = Path(root)
    files = {root / "API.md": render_index()}
    files.update({root / "api" / f"{p.slug}.md": render_page(p) for p in PAGES})
    return files


def write(root: str | Path) -> list[Path]:
    """Write the generated API files below ``root`` (the ``docs`` directory).

    Parameters
    ----------
    root : path
        The ``docs`` directory.

    Returns
    -------
    list of Path
        The files written.
    """
    files = generate(root)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return list(files)
