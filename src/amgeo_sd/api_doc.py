# ------------------------------------------------------------------ parsing


@dataclass
class Entry:
    """One documented parameter / attribute / return value."""

    names: list[str]
    type: str
    text: str


@dataclass
class Doc:
    """A parsed NumPy-style docstring."""

    summary: str = ""
    body: str = ""
    sections: dict[str, list[Entry]] = field(default_factory=dict)
    raw: dict[str, str] = field(default_factory=dict)


def parse_docstring(text: str | None) -> Doc:
    """Split a NumPy-style docstring into summary, body and sections.

    Parameters
    ----------
    text : str or None
        The docstring (``inspect.getdoc`` form).

    Returns
    -------
    Doc
        ``summary`` (first paragraph), ``body`` (text before the first section), and for each known section its
        entries (``name : type`` followed by an indented description) in ``sections`` and its text in ``raw``.
    """
    doc = Doc()
    if not text:
        return doc
    lines = inspect.cleandoc(text).splitlines()
    heads = [
        i
        for i in range(len(lines) - 1)
        if lines[i].strip() in SECTION_NAMES and re.fullmatch(r"-{3,}", lines[i + 1].strip())
    ]
    first = heads[0] if heads else len(lines)
    body = "\n".join(lines[:first]).strip()
    doc.summary = " ".join(body.split("\n\n")[0].split())
    doc.body = "\n\n".join(body.split("\n\n")[1:]).strip()
    for k, h in enumerate(heads):
        end = heads[k + 1] if k + 1 < len(heads) else len(lines)
        name, content = lines[h].strip(), lines[h + 2 : end]
        doc.raw[name] = "\n".join(content).strip()
        if name in ("Parameters", "Attributes", "Returns", "Yields", "Raises"):
            doc.sections[name] = _entries(content, returns=name in ("Returns", "Yields", "Raises"))
    return doc


def _entries(lines: list[str], returns: bool) -> list[Entry]:
    entries: list[Entry] = []
    for line in lines:
        if not line.strip():
            if entries:
                entries[-1].text += "\n"
            continue
        if not line.startswith((" ", "\t")):
            if returns and " : " not in line and not line.rstrip().endswith(" :"):
                entries.append(Entry([], line.strip(), ""))  # a bare type
                continue
            head, _, typ = line.partition(" : ") if " : " in line else (line.rstrip(" :"), "", "")
            entries.append(Entry([n.strip() for n in head.split(",") if n.strip()], typ.strip(), ""))
        elif entries:
            entries[-1].text += line.strip() + " "
    for e in entries:
        e.text = re.sub(r"\s*\n\s*", "  \n", e.text.strip()) if "\n" in e.text.strip() else e.text.strip()
    return entries


# ------------------------------------------------------------------ introspection


def public_names(module_name: str, names: tuple[str, ...] | None = None) -> list[str]:
    """Return the documented names of a module (its ``__all__`` unless ``names`` is given)."""
    mod = importlib.import_module(module_name)
    return list(names if names is not None else mod.__all__)


def _methods(cls: type) -> list[tuple[str, object]]:
    out = []
    for name, member in cls.__dict__.items():
        if name.startswith("_") or name in ("to_dict", "from_dict") and cls.__name__ in FIELDS_IN_REFERENCE:
            continue
        if isinstance(member, property):
            out.append((name, member))
        elif isinstance(member, (staticmethod, classmethod)):
            out.append((name, member.__func__))
        elif inspect.isfunction(member):
            out.append((name, member))
    return out


def _params(sig: inspect.Signature) -> list[inspect.Parameter]:
    return [p for p in sig.parameters.values() if p.name not in ("self", "cls")]


def _default(p: inspect.Parameter) -> str:
    if p.default is inspect.Parameter.empty:
        return "required"
    text = repr(p.default)
    if "\n" in text or len(text) > 100:
        return "see description"
    return f"`{text}`"


def _is_callable_doc(obj: object) -> bool:
    return inspect.isclass(obj) or inspect.isfunction(obj)


def _check_function(label: str, fn, doc: Doc, out: list[str], needs_returns: bool = True) -> None:
    if not doc.summary:
        out.append(f"{label}: no docstring")
        return
    sig = inspect.signature(fn)
    want = [p.name for p in _params(sig)]
    have = [n.lstrip("*") for e in doc.sections.get("Parameters", []) for n in e.names]
    for n in want:
        if n not in have:
            out.append(f"{label}: parameter `{n}` is not documented")
    for n in have:
        if n not in want:
            out.append(f"{label}: documented parameter `{n}` is not in the signature")
    for e in doc.sections.get("Parameters", []):
        if not e.type or not e.text:
            out.append(f"{label}: parameter {e.names} needs a type and a description")
    ret = sig.return_annotation
    if needs_returns and ret not in (inspect.Signature.empty, "None", None) and "Returns" not in doc.sections:
        out.append(f"{label}: no Returns section")


def _check_class(label: str, cls: type, doc: Doc, out: list[str]) -> None:
    if not doc.summary:
        out.append(f"{label}: no docstring")
        return
    if cls.__name__ in FIELDS_IN_REFERENCE:
        return
    if dataclasses.is_dataclass(cls):
        want = [f.name for f in dataclasses.fields(cls)]
        have = [n for e in doc.sections.get("Attributes", []) for n in e.names]
        for n in want:
            if n not in have:
                out.append(f"{label}: field `{n}` is not documented under Attributes")
        for n in have:
            if n not in want:
                out.append(f"{label}: documented attribute `{n}` is not a field")
    else:
        _check_function(label, cls.__init__, doc, out, needs_returns=False)
    for name, member in _methods(cls):
        target = member.fget if isinstance(member, property) else member
        mdoc = parse_docstring(inspect.getdoc(target))
        if isinstance(member, property):
            if not mdoc.summary:
                out.append(f"{label}.{name}: no docstring")
        else:
            _check_function(f"{label}.{name}", member, mdoc, out)


def problems() -> list[str]:
    """List every documentation gap of the public API (empty when complete).

    Returns
    -------
    list of str
        One message per missing docstring, undocumented parameter, stale parameter name or missing Returns section.
    """
    out: list[str] = []
    for page in PAGES:
        mod = importlib.import_module(page.module)
        for name in public_names(page.module, page.names):
            obj = getattr(mod, name)
            label = f"{page.module}.{name}"
            if inspect.isclass(obj):
                _check_class(label, obj, parse_docstring(inspect.getdoc(obj)), out)
            elif inspect.isfunction(obj):
                _check_function(label, obj, parse_docstring(inspect.getdoc(obj)), out)
            elif label not in CONSTANT_DOCS:
                out.append(f"{label}: constant has no entry in CONSTANT_DOCS")
    return out


# ------------------------------------------------------------------ rendering

_ROLE = re.compile(r":(?:func|class|meth|data|mod|attr|obj):`~?([\w.]+)`")


def _index() -> dict[str, str]:
    """Map ``Name`` and ``Class.method`` of every documented object to the page and anchor it is documented at."""
    found: dict[str, str] = {}
    for page in PAGES:
        mod = importlib.import_module(page.module)
        for name in public_names(page.module, page.names):
            obj = getattr(mod, name)
            found[name] = f"{page.slug}.md#{_anchor(name) if _is_callable_doc(obj) else 'constants'}"
            if inspect.isclass(obj) and name not in FIELDS_IN_REFERENCE:
                for method, _ in _methods(obj):
                    found[f"{name}.{method}"] = f"{page.slug}.md#{_anchor(f'{name}.{method}')}"
    return found


def _md(text: str) -> str:
    """Turn the Sphinx roles used in docstrings (``:func:`name```) into Markdown links to the documented names."""
    index = _index()

    def link(m: re.Match) -> str:
        parts = m.group(1).split(".")
        for n in (2, 1):
            key = ".".join(parts[-n:])
            if key in index:
                return f"[`{key}`]({index[key]})"
        return f"`{parts[-1]}`"

    return _ROLE.sub(link, text)


def _cell(text: str) -> str:
    return _md(text).replace("|", "\\|").replace("\n", " ").strip()


def _table(rows: list[tuple[str, str, str, str]], default: bool = True, first: str = "Parameter") -> list[str]:
    if default:
        head = [f"| {first} | Type | Default | Description |", "|---|---|---|---|"]
        return head + [f"| {a} | {_cell(b)} | {_cell(c)} | {_cell(d)} |" for a, b, c, d in rows]
    head = ["| Name | Type | Description |", "|---|---|---|"]
    return head + [f"| {a} | {_cell(b)} | {_cell(d)} |" for a, b, _, d in rows]


def _signature(name: str, fn, cls: bool = False) -> str:
    sig = inspect.signature(fn)
    items = [_fmt(p) for p in _params(sig)]
    kinds = [p.kind for p in _params(sig)]
    if inspect.Parameter.KEYWORD_ONLY in kinds and inspect.Parameter.VAR_POSITIONAL not in kinds:
        items.insert(kinds.index(inspect.Parameter.KEYWORD_ONLY), "*")  # everything after this is keyword-only
    inline = f"{name}({', '.join(items)})"
    ret = "" if cls or sig.return_annotation is inspect.Signature.empty else f" -> {sig.return_annotation}"
    if len(inline + ret) <= 100:
        return inline + ret
    body = "".join(f"    {i},\n" for i in items)
    return f"{name}(\n{body}){ret}"


def _fmt(p: inspect.Parameter) -> str:
    star = {p.VAR_POSITIONAL: "*", p.VAR_KEYWORD: "**"}.get(p.kind, "")
    text = f"{star}{p.name}"
    if p.annotation is not p.empty:
        text += f": {p.annotation}"
    if p.default is not p.empty:
        d = repr(p.default)
        text += f" = {d if len(d) <= 100 and chr(10) not in d else '...'}"
    return text


def _param_rows(
    doc: Doc, sig: inspect.Signature | None, fields_: dict | None = None
) -> list[tuple[str, str, str, str]]:
    defaults = {p.name: _default(p) for p in _params(sig)} if sig else {}
    rows = []
    for e in doc.sections.get("Parameters", []) or doc.sections.get("Attributes", []):
        found = []
        for n in e.names:
            d = defaults.get(n, "")
            if fields_ and n in fields_:
                f = fields_[n]
                if f.default is not dataclasses.MISSING:
                    d = f"`{f.default!r}`"
                elif f.default_factory is not dataclasses.MISSING:
                    d = "empty" if f.default_factory.__name__ != "<lambda>" else "empty array"
                else:
                    d = "required"
            found.append(d)
        # entries such as ``start, end : datetime`` share one row; equal defaults are shown once
        default = found[0] if len(set(found)) == 1 else " / ".join(found)
        rows.append((", ".join(f"`{n}`" for n in e.names), e.type, default, e.text))
    return rows


def _render_object(level: int, qualname: str, kind: str, obj, doc: Doc, sig_text: str | None, sig, fields_=None):
    h = "#" * level
    lines = [f"{h} `{qualname}`", ""]
    if sig_text:
        lines += ["```python", sig_text, "```", ""]
    if doc.summary:
        lines += [_md(doc.summary), ""]
    if doc.body:
        lines += [_md(doc.body), ""]
    rows = _param_rows(doc, sig, fields_)
    if rows:
        title = "Parameters" if doc.sections.get("Parameters") else "Attributes"
        lines += [f"**{title}**", ""] + _table(rows, True, "Parameter" if title == "Parameters" else "Attribute") + [""]
    for sect, label in (("Returns", "Returns"), ("Yields", "Yields"), ("Raises", "Raises")):
        entries = doc.sections.get(sect)
        if entries:
            lines += [f"**{label}**", ""]
            for e in entries:
                who = ", ".join(f"`{n}`" for n in e.names)
                typ = f"*{e.type}*" if e.type else ""
                head = f"{who} : {typ}" if who else typ
                lines.append(f"- {head}" + (f" — {_md(e.text)}" if e.text else ""))
            lines.append("")
    for sect in ("Notes", "Examples"):
        if sect in doc.raw:
            lines += [f"**{sect}**", ""]
            lines += [_example_block(doc.raw[sect]) if sect == "Examples" else _md(doc.raw[sect]), ""]
    return lines


def _example_block(text: str) -> str:
    if text.lstrip().startswith(">>>") or "\n    " in text or text.startswith("    "):
        return "```python\n" + "\n".join(re.sub(r"^>>> ?|^\.\.\. ?", "", ln) for ln in text.splitlines()) + "\n```"
    return text


def render_page(page: Page) -> str:
    """Return the Markdown of one API page.

    Parameters
    ----------
    page : Page
        Which module (and names) to document.

    Returns
    -------
    str
        The page, with a contents table, one section per public name and a parameter table per callable.
    """
    mod = importlib.import_module(page.module)
    names = public_names(page.module, page.names)
    objs = {n: getattr(mod, n) for n in names}
    lines = [
        HEADER,
        f"# {page.title}",
        "",
        "Back to the [API overview](../API.md) · [README](../../README.md) · [usage guide](../USAGE.md) · "
        "[parameter reference](../PARAMETERS.md).",
        "",
        f"`{page.module}` — {page.summary}",
        "",
    ]
    constants = [(n, o) for n, o in objs.items() if not _is_callable_doc(o)]
    callables = [(n, o) for n, o in objs.items() if _is_callable_doc(o)]
    lines += ["| Name | What it is |", "|---|---|"]
    for n, o in callables:
        lines.append(f"| [`{n}`](#{_anchor(n)}) | {_cell(parse_docstring(inspect.getdoc(o)).summary)} |")
    for n, _ in constants:
        lines.append(f"| [`{n}`](#constants) | {_cell(CONSTANT_DOCS[f'{page.module}.{n}'])} |")
    lines.append("")
    for n, o in callables:
        doc = parse_docstring(inspect.getdoc(o))
        if inspect.isclass(o):
            lines += _render_class(n, o, doc)
        else:
            lines += _render_object(2, n, "function", o, doc, _signature(n, o), inspect.signature(o))
    if constants:
        lines += ["## Constants", "", "| Name | Value | Meaning |", "|---|---|---|"]
        for n, o in constants:
            val = repr(o).replace("\n", " ")
            val = val if len(val) <= 60 else val[:57] + "..."
            lines.append(f"| `{n}` | `{_cell(val)}` | {_cell(CONSTANT_DOCS[f'{page.module}.{n}'])} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _anchor(name: str) -> str:
    return re.sub(r"[^a-z0-9_-]", "", name.lower())


def _render_class(name: str, cls: type, doc: Doc) -> list[str]:
    if name in FIELDS_IN_REFERENCE:
        lines = [f"## `{name}`", "", _md(doc.summary), ""]
        lines += [
            "Its fields are listed, with defaults and allowed values, in the [parameter reference](../PARAMETERS.md).",
            "",
        ]
    elif dataclasses.is_dataclass(cls):
        flds = {f.name: f for f in dataclasses.fields(cls)}
        lines = _render_object(2, name, "dataclass", cls, doc, _signature(name, cls, cls=True), None, flds)
    else:
        lines = _render_object(
            2, name, "class", cls, doc, _signature(name, cls.__init__, cls=True), inspect.signature(cls.__init__)
        )
    for mname, member in _methods(cls):
        if name in FIELDS_IN_REFERENCE:
            continue
        if isinstance(member, property):
            mdoc = parse_docstring(inspect.getdoc(member.fget))
            lines += [f"### `{name}.{mname}`  (property)", "", _md(mdoc.summary), ""]
        else:
            mdoc = parse_docstring(inspect.getdoc(member))
            lines += _render_object(
                3, f"{name}.{mname}", "method", member, mdoc, _signature(mname, member), inspect.signature(member)
            )
    return lines


